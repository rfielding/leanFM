#!/usr/bin/env python3
"""Derive the book's state-machine figures from the checked task catalog.

Input:  spec/tasks.json, written by the canonical check (`make spec-check`) from
        Project.Requirements.requirements; nothing here is drawn by hand.
Output: renders/<task>.light.pdf and renders/<task>.dark.pdf (Graphviz), and
        renders/views.tex, the appendix that includes them. The book picks the
        dark or light copy to match the PDF being built.

Run from the project root: python3 book/views.py   (or `make views`)
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "renders"
THEMES = {
    "light": {"bg": "transparent", "fg": "#1f2933", "edge": "#52606d", "term": "#1f6f43", "label": "#5b3cc4"},
    "dark": {"bg": "transparent", "fg": "#f0ede4", "edge": "#9aa5b1", "term": "#4ade80", "label": "#c4b5fd"},
}


def q(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def dot(task, theme):
    c = THEMES[theme]
    lines = [
        "digraph task {",
        "rankdir=LR;",
        f'graph [bgcolor="{c["bg"]}", pad=0.2];',
        f'node [shape=box, style=rounded, fontname="Helvetica", fontsize=11, color="{c["fg"]}", fontcolor="{c["fg"]}"];',
        f'edge [fontname="Helvetica", fontsize=10, color="{c["edge"]}", fontcolor="{c["label"]}"];',
        f'"__start" [shape=point, width=0.12, color="{c["fg"]}"];',
        f'"__start" -> {q(task["entry"])};',
    ]
    for s in task["states"]:
        extra = f', peripheries=2, color="{c["term"]}"' if s.get("terminal") else ""
        lines.append(f'{q(s["id"])} [label={q(s.get("label") or s["id"])}{extra}];')
    for t in task["transitions"]:
        lines.append(f'{q(t["src"])} -> {q(t["dst"])} [label={q(t["message"])}];')
    lines.append("}")
    return "\n".join(lines) + "\n"


def tex_escape(text):
    for a, b in [("\\", r"\textbackslash{}"), ("_", r"\_"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("$", r"\$")]:
        text = text.replace(a, b)
    return text


def main():
    catalog = json.loads((ROOT / "spec/tasks.json").read_text())
    OUT.mkdir(exist_ok=True)
    tex = ["% Generated by book/views.py from spec/tasks.json; do not edit by hand.",
           r"\chapter{Task catalog}", r"\label{ch:catalog}",
           "Every task of the checked requirements, as the state machine LeanFM derives from its grammar. "
           "Double borders mark terminal states. Regenerate with \\texttt{make views}.", ""]
    for task in catalog["tasks"]:
        for theme in THEMES:
            src = OUT / f"{task['id']}.{theme}.dot"
            src.write_text(dot(task, theme))
            subprocess.run(["dot", "-Tpdf", str(src), "-o", str(src.with_suffix(".pdf"))], check=True)
        alt = "; ".join(f"{t['src']} to {t['dst']}: {t['message']}" for t in task["transitions"])
        tex += [r"\begin{figure}[ht]", r"\centering",
                r"\BeginAccSupp{method=escape,ActualText={" + tex_escape(alt) + "}}",
                r"\includegraphics[width=\textwidth,height=0.38\textheight,keepaspectratio]{../renders/"
                + task["id"] + r".\viewtheme.pdf}",
                r"\EndAccSupp{}",
                r"\caption{\texttt{" + tex_escape(task["id"]) + "}: " + tex_escape(task["title"]) + "}",
                r"\label{fig:" + task["id"] + "}",
                r"\end{figure}", ""]
    (OUT / "views.tex").write_text("\n".join(tex))
    print(f"renders/: {len(catalog['tasks'])} tasks, light and dark")


if __name__ == "__main__":
    main()
