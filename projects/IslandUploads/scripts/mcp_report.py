"""Typeset the MCP answers in reports/mcp/results.json for the book.

Writes reports/mcp/{verdicts,readings,classify,session-excerpt}.tex and, when `mmdc` is on PATH,
one sequence diagram per counterexample that check_trace drew, light and dark (PNG keeps the
background; Mermaid's PDF output is always white).

Run from projects/IslandUploads: python3 scripts/mcp_report.py
"""
import json, re, shutil, subprocess

OUT = "reports/mcp"
r = json.load(open(f"{OUT}/results.json"))

def tex(s):
    return (s or "").replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("&", "\\&").replace("%", "\\%").replace("#", "\\#")

def evidence(entry):
    ev = entry.get("evidence") or {}
    kind = ev.get("kind")
    if kind == "exhaustive":
        n = re.search(r"(\d+)", ev.get("note", ""))
        return f"none, over all {n.group(1)} nodes" if n else "exhaustive"
    if kind in ("witness", "counterexample"):
        msgs = [p["message"] for p in ev.get("path", []) if p["message"]]
        tail = ", then around again" if ev.get("loopsBackTo") is not None else ""
        return f"{kind}: \\texttt{{{tex(', '.join(msgs))}{tail}}}"
    return tex(kind or "")

say = {k: v["say"] for k, v in r["explain"].items()}
rows = [f"\\texttt{{{tex(k.split('.')[0])}}} & {tex(say[k.split('.')[1]])} & \\textbf{{{v['verdict']}}} & {evidence(v)} \\\\"
        for k, v in r["ctl"].items()]
open(f"{OUT}/verdicts.tex", "w").write(
    "% Generated by scripts/mcp_report.py from reports/mcp/results.json.\n"
    "\\begin{longtable}{@{}p{.2\\textwidth}p{.25\\textwidth}p{.1\\textwidth}p{.38\\textwidth}@{}}\n\\toprule\n"
    "model & question & verdict & evidence \\\\\n\\midrule\n\\endhead\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{longtable}\n")

items = [f"\\item[\\texttt{{{k}}}] {tex(v['reading'])}." + (f" \\emph{{Lint:}} {tex(v['lints'][0])}" if v["lints"] else "")
         for k, v in r["explain"].items()]
open(f"{OUT}/readings.tex", "w").write("% Generated by scripts/mcp_report.py.\n\\begin{description}\n" + "\n".join(items) + "\n\\end{description}\n")

cls = [f"\\item[{tex(a['class'])}] {tex(a['atom'])}" for a in r["classify"]["atoms"]]
open(f"{OUT}/classify.tex", "w").write("% Generated by scripts/mcp_report.py.\n\\begin{description}\n" + "\n".join(cls) + "\n\\end{description}\n")

src = open("spec/Session.lean").read()
blocks = re.findall(r"^protocol (?:Upload|Download|Replicate|PullPage) .*?^}\n", src, re.S | re.M)
ascii = lambda t: t.replace("∧", "/\\").replace("∨", "\\/").replace("≥", ">=").replace("≤", "<=")
open(f"{OUT}/session-excerpt.tex", "w").write(
    "% Generated by scripts/mcp_report.py from spec/Session.lean (logic symbols in ASCII).\n\\begin{Verbatim}[fontsize=\\small]\n"
    + "\n".join(ascii(b) for b in blocks) + "\\end{Verbatim}\n")
door = re.findall(r"^protocol (?:Forward|Socket) .*?^}\n", src, re.S | re.M)
open(f"{OUT}/session-door.tex", "w").write(
    "% Generated by scripts/mcp_report.py from spec/Session.lean (logic symbols in ASCII).\n\\begin{Verbatim}[fontsize=\\small]\n"
    + "\n".join(ascii(b) for b in door) + "\\end{Verbatim}\n")

if shutil.which("mmdc"):
    for key, t in r["traces"].items():
        name = key.replace(".", "-")
        open(f"{OUT}/{name}.mmd", "w").write(t["sequenceDiagram"] + "\n")
        for suffix, theme, bg in [("", "default", "white"), ("-dark", "dark", "#091117")]:
            subprocess.run(["mmdc", "-q", "-i", f"{OUT}/{name}.mmd", "-o", f"{OUT}/{name}{suffix}.png",
                            "-t", theme, "-b", bg, "-s", "3"], check=True)
print("ok:", len(rows), "verdicts,", len(r["traces"]), "diagrams")
