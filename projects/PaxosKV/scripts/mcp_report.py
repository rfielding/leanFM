"""Turn the MCP answers in reports/mcp/results.json into the book's tables and figures.

Writes reports/mcp/verdicts.tex, reports/mcp/session-excerpt.tex and, when `mmdc` (Mermaid CLI)
is on PATH, conflict-sequence{,-dark}.png and conflict-causal{,-dark}.png from the diagrams that
check_trace returned. Nothing here decides a verdict; it only typesets what the server said.

Run from projects/PaxosKV: python3 scripts/mcp_report.py
"""
import json, os, re, shutil, subprocess

OUT = "reports/mcp"
r = json.load(open(f"{OUT}/results.json"))

def tex(s):
    return (s or "").replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("&", "\\&").replace("%", "\\%").replace("#", "\\#")

def path_of(entry):
    ev = entry.get("path") or (entry.get("evidence") or {}).get("path") or []
    msgs = [p["message"] for p in ev if p["message"]]
    loop = (entry.get("evidence") or {}).get("loopsBackTo")
    text = ", ".join(msgs)
    if loop is not None:
        text += ", then nothing more"
    return text

def evidence(entry):
    ev = entry.get("evidence") or {}
    kind = ev.get("kind")
    if kind == "exhaustive":
        n = re.search(r"(\d+)", ev.get("note", ""))
        return f"none, over all {n.group(1)} nodes" if n else "exhaustive"
    if kind in ("witness", "counterexample"):
        return f"{kind}: \\texttt{{{tex(path_of(entry))}}}"
    return tex(kind or "")

say = {k: v["say"] for k, v in r["explain"].items()}
rows = []
for key, entry in r["ctl"].items():
    variant, name = key.split(".")
    rows.append(f"\\texttt{{{variant}}} & {tex(say[name])} & \\textbf{{{entry['verdict']}}} & {evidence(entry)} \\\\")
with open(f"{OUT}/verdicts.tex", "w") as f:
    f.write("% Generated by scripts/mcp_report.py from reports/mcp/results.json.\n")
    f.write("\\begin{longtable}{@{}p{.13\\textwidth}p{.27\\textwidth}p{.11\\textwidth}p{.43\\textwidth}@{}}\n\\toprule\n")
    f.write("model & question & verdict & evidence \\\\\n\\midrule\n\\endhead\n")
    f.write("\n".join(rows) + "\n\\bottomrule\n\\end{longtable}\n")

readings = [f"\\item[\\texttt{{{k}}}] {tex(v['reading'])}." + (f" \\emph{{Lint:}} {tex(v['lints'][0])}" if v["lints"] else "")
            for k, v in r["explain"].items()]
with open(f"{OUT}/readings.tex", "w") as f:
    f.write("% Generated by scripts/mcp_report.py: explain_formula readings.\n\\begin{description}\n")
    f.write("\n".join(readings) + "\n\\end{description}\n")

cls = [f"\\item[{tex(a['class'])}] {tex(a['atom'])}" + (f" (proposes event \\texttt{{{tex(a['proposedEvent']['message'])}}})" if a.get("proposedEvent") else "")
       for a in r["classify"]["atoms"]]
cls.append(f"\\item[{tex(r['classifyAgreement']['atoms'][0]['class'])}] the agreement formula: {tex(r['classifyAgreement']['reading'])}")
with open(f"{OUT}/classify.tex", "w") as f:
    f.write("% Generated by scripts/mcp_report.py: classify_requirement answers.\n\\begin{description}\n")
    f.write("\n".join(cls) + "\n\\end{description}\n")

src = open("spec/Session.lean").read()
blocks = re.findall(r"^protocol QuorumWrite.*?^}\n", src, re.S | re.M)
with open(f"{OUT}/session-excerpt.tex", "w") as f:
    f.write("% Generated by scripts/mcp_report.py from spec/Session.lean.\n\\begin{Verbatim}[fontsize=\\small]\n")
    f.write("".join(blocks) + "\\end{Verbatim}\n")

trace = r["traces"].get("broken.conflict")
if trace and shutil.which("mmdc"):
    for name, text in [("conflict-sequence", trace["sequenceDiagram"]), ("conflict-causal", trace["causalGraph"])]:
        open(f"{OUT}/{name}.mmd", "w").write(text + "\n")
        for suffix, theme, bg in [("", "default", "white"), ("-dark", "dark", "#091117")]:
            # PNG keeps the background colour; Mermaid's PDF output always paints white
            subprocess.run(["mmdc", "-q", "-i", f"{OUT}/{name}.mmd", "-o", f"{OUT}/{name}{suffix}.png",
                            "-t", theme, "-b", bg, "-s", "3"], check=True)
print("ok:", len(rows), "verdicts")
